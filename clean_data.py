import pandas as pd

# 1. Завантаження сирих даних
df = pd.read_csv("raw.csv", encoding="utf-8-sig")

# 2. Фільтрація потрібного показника та розрізів
df = df[
    (df["Показник"] == "Кількість активних підприємств") &
    (df["Категорія розрізу"] == "Вид економічної діяльності") &
    (df["Стать керівника"].isin(["Чоловіки", "Жінки"]))
].copy()

# 3. Видалення порожніх значень
df = df.dropna(subset=["Значення cпостереження"]).copy()

# 4. Перейменування колонок
df = df.rename(columns={
    "Територіальний розріз": "region",
    "Розріз": "activity",
    "Стать керівника": "sex",
    "Період": "year",
    "Значення cпостереження": "enterprises_count"
})

# 5. Перетворення типів
df["year"] = pd.to_numeric(df["year"], errors="coerce")
df["enterprises_count"] = pd.to_numeric(df["enterprises_count"], errors="coerce")

# 6. Видалення рядків після конвертації, якщо з'явились NaN
df = df.dropna(subset=["year", "enterprises_count"]).copy()

# 7. Приведення типів
df["year"] = df["year"].astype(int)
df["enterprises_count"] = df["enterprises_count"].astype(int)

# 8. Список верхньорівневих категорій КВЕД
top_level_activities = [
    "Сільське господарство, лісове господарство та рибне господарство",
    "Добувна промисловість і розроблення кар'єрів",
    "Переробна промисловість",
    "Постачання електроенергії, газу, пари та кондиційованого повітря",
    "Водопостачання; каналізація, поводження з відходами",
    "Будівництво",
    "Оптова та роздрібна торгівля; ремонт автотранспортних засобів і мотоциклів",
    "Транспорт, складське господарство, поштова та кур'єрська діяльність",
    "Тимчасове розміщування й організація харчування",
    "Інформація та телекомунікації",
    "Фінансова та страхова діяльність",
    "Операції з нерухомим майном",
    "Професійна, наукова та технічна діяльність",
    "Діяльність у сфері адміністративного та допоміжного обслуговування",
    "Державне управління й оборона; обов'язкове соціальне страхування",
    "Освіта",
    "Охорона здоров'я та надання соціальної допомоги",
    "Мистецтво, спорт, розваги та відпочинок",
    "Надання інших видів послуг",
    "Діяльність домашніх господарств",
    "Діяльність екстериторіальних організацій і органів",
]

# 9. Фільтрація по верхньорівневих галузях
df = df[df["activity"].isin(top_level_activities)].copy()

# 10. Прибираємо загальний підсумок по країні
df = df[df["region"] != "Україна"].copy()

# 11. Збереження очищених даних
df.to_csv("data_processed/enterprises_clean.csv", index=False, encoding="utf-8-sig")

# 12. Коротка перевірка
print("Clean dataset saved to data_processed/enterprises_clean.csv")
print("Shape:", df.shape)
print("Regions:", df["region"].nunique())
print("Activities:", df["activity"].nunique())
print("Years:", df["year"].min(), "-", df["year"].max())
print("Sex values:", df["sex"].unique())


